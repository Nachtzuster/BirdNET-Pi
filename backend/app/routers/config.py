@router.put("/config")
async def update_config(
    config_update: ConfigUpdate,
    user: str = Depends(verify_credentials),
    settings: Settings = Depends(get_settings),
):
    """Update configuration.

    Requires authentication. Only updates fields that are provided.
    """
    config_path = settings.config_path
    previous_model = settings.model
    previous_language = settings.database_lang
    installed_models = list_installed_selectable_models()

    if config_update.model is not None and config_update.model not in installed_models:
        raise HTTPException(
            status_code=400,
            detail={
                "message": f"Unsupported model: {config_update.model}",
                "available_models": installed_models,
            },
        )

    # Read current config file
    try:
        with open(config_path, 'r') as f:
            contents = f.read()
    except FileNotFoundError:
        raise HTTPException(status_code=500, detail="Configuration file not found")
    except PermissionError:
        raise HTTPException(status_code=500, detail="Cannot read configuration file")

    # Map of field names to config keys
    field_map = {
        'site_name': 'SITE_NAME',
        'latitude': 'LATITUDE',
        'longitude': 'LONGITUDE',
        'database_lang': 'DATABASE_LANG',
        'color_scheme': 'COLOR_SCHEME',
        'update_channel': 'UPDATE_CHANNEL',
        'info_site': 'INFO_SITE',
        'model': 'MODEL',
        'sf_thresh': 'SF_THRESH',
        'data_model_version': 'DATA_MODEL_VERSION',
        'confidence': 'CONFIDENCE',
        'sensitivity': 'SENSITIVITY',
        'overlap': 'OVERLAP',
        'birdweather_id': 'BIRDWEATHER_ID',
        'flickr_api_key': 'FLICKR_API_KEY',
        'flickr_filter_email': 'FLICKR_FILTER_EMAIL',
        'image_provider': 'IMAGE_PROVIDER',
        'caddy_password': 'CADDY_PWD',
        'birdnetpi_url': 'BIRDNETPI_URL',
        'rtsp_stream': 'RTSP_STREAM',
        'rtsp_stream_to_livestream': 'RTSP_STREAM_TO_LIVESTREAM',
        'activate_freqshift_in_livestream': 'ACTIVATE_FREQSHIFT_IN_LIVESTREAM',
        'apprise_notification_title': 'APPRISE_NOTIFICATION_TITLE',
        'apprise_notify_each_detection': 'APPRISE_NOTIFY_EACH_DETECTION',
        'apprise_notify_new_species': 'APPRISE_NOTIFY_NEW_SPECIES',
        'apprise_notify_new_species_each_day': 'APPRISE_NOTIFY_NEW_SPECIES_EACH_DAY',
        'apprise_weekly_report': 'APPRISE_WEEKLY_REPORT',
        'apprise_minimum_seconds_between_notifications_per_species': 'APPRISE_MINIMUM_SECONDS_BETWEEN_NOTIFICATIONS_PER_SPECIES',
        'apprise_only_notify_species_names': 'APPRISE_ONLY_NOTIFY_SPECIES_NAMES',
        'apprise_only_notify_species_names_2': 'APPRISE_ONLY_NOTIFY_SPECIES_NAMES_2',
        'privacy_threshold': 'PRIVACY_THRESHOLD',
        'full_disk': 'FULL_DISK',
        'purge_threshold': 'PURGE_THRESHOLD',
        'max_files_species': 'MAX_FILES_SPECIES',
        'rec_card': 'REC_CARD',
        'channels': 'CHANNELS',
        'recording_length': 'RECORDING_LENGTH',
        'extraction_length': 'EXTRACTION_LENGTH',
        'audiofmt': 'AUDIOFMT',
        'silence_update_indicator': 'SILENCE_UPDATE_INDICATOR',
        'automatic_update': 'AUTOMATIC_UPDATE',
        'raw_spectrogram': 'RAW_SPECTROGRAM',
        'rare_species_threshold': 'RARE_SPECIES_THRESHOLD',
        'custom_image': 'CUSTOM_IMAGE',
        'custom_image_title': 'CUSTOM_IMAGE_TITLE',
        'freqshift_tool': 'FREQSHIFT_TOOL',
        'freqshift_hi': 'FREQSHIFT_HI',
        'freqshift_lo': 'FREQSHIFT_LO',
        'freqshift_reconnect_delay': 'FREQSHIFT_RECONNECT_DELAY',
        'freqshift_pitch': 'FREQSHIFT_PITCH',
        'log_level_birdnet_recording_service': 'LogLevel_BirdnetRecordingService',
        'log_level_live_audio_stream_service': 'LogLevel_LiveAudioStreamService',
        'log_level_spectrogram_viewer_service': 'LogLevel_SpectrogramViewerService',
    }

    # Update config values
    updates = config_update.model_dump(exclude_unset=True)
    file_updates: dict[str, str] = {}
    if 'apprise_config' in updates:
        file_updates[APPRISE_CONFIG_FILENAME] = updates.pop('apprise_config') or ''
    if 'apprise_notification_body' in updates:
        file_updates[APPRISE_BODY_FILENAME] = updates.pop('apprise_notification_body') or ''

    for field, value in updates.items():
        if field not in field_map:
            continue

        key = field_map[field]
        if field == 'extraction_length' and value is None:
            new_value = f'{key}=""'
        elif value is None:
            continue
        else:
            new_value = serialize_config_value(field, key, value)

        # Replace or add the setting
        pattern = rf'^{re.escape(key)}=.*$'
        if re.search(pattern, contents, re.MULTILINE):
            contents = re.sub(pattern, new_value, contents, flags=re.MULTILINE)
        else:
            contents += f'\n{new_value}'

    # Write updated config
    try:
        with open(config_path, 'w') as f:
            f.write(contents)
    except PermissionError:
        # Try with sudo
        with tempfile.NamedTemporaryFile(mode='w', delete=False) as tmp:
            tmp.write(contents)
            tmp_path = tmp.name

        try:
            subprocess.run(['sudo', 'cp', tmp_path, config_path], check=True)
        finally:
            os.unlink(tmp_path)

    for filename, file_contents in file_updates.items():
        write_notification_file(settings, filename, file_contents)

    # Reload settings
    settings.reload()
    applied_actions = []

    if settings.model != previous_model or settings.database_lang != previous_language:
        sync_language_labels(settings)
        applied_actions.append('labels_updated')

    if 'birdnetpi_url' in updates or 'caddy_password' in updates:
        update_caddy_config(settings)
        applied_actions.append('caddy_reloaded')

    restart_services(settings)
    applied_actions.append('services_restarted')

    return {
        "message": "Configuration updated and services restarted",
        "updated_fields": list(updates.keys()),
        "applied_actions": applied_actions,
    }


@router.post("/config/test-notification", response_model=NotificationResponse)
async def test_notification(
    request: TestNotificationRequest,
    user: str = Depends(verify_credentials),
    settings: Settings = Depends(get_settings),
):
    """Send a test notification.

    Requires authentication.
    """
    # Use the existing send_test_notification.py script
    script_path = os.path.join(settings.base_path, 'scripts', 'send_test_notification.py')
    python_path = os.path.join(settings.base_path, 'birdnet', 'bin', 'python3')

    if not os.path.exists(script_path):
        raise HTTPException(status_code=500, detail="Notification script not found")

    title = request.title or settings.apprise_notification_title
    body_contents = request.body if request.body is not None else read_notification_file(settings, APPRISE_BODY_FILENAME)
    config_contents = request.config if request.config is not None else read_notification_file(settings, APPRISE_CONFIG_FILENAME)

    with tempfile.NamedTemporaryFile(mode='w', delete=False, encoding='utf-8') as body_file:
        body_file.write(body_contents)
        body_path = body_file.name

    with tempfile.NamedTemporaryFile(mode='w', delete=False, encoding='utf-8') as config_file:
        config_file.write(config_contents)
        config_path = config_file.name

    cmd = [python_path, script_path, '--config', config_path, '--title', title, '--body', body_path]

    try:
        result = subprocess.run(cmd, capture_output=True, text=True, timeout=30)

        if result.returncode == 0:
            return NotificationResponse(
                success=True,
                message="Test notification sent successfully",
            )
        else:
            return NotificationResponse(
                success=False,
                message=f"Notification failed: {result.stderr or result.stdout}",
            )
    except subprocess.TimeoutExpired:
        return NotificationResponse(
            success=False,
            message="Notification timed out",
        )
    except Exception as e:
        return NotificationResponse(
            success=False,
            message=f"Error sending notification: {str(e)}",
        )
    finally:
        for path in (body_path, config_path):
            try:
                os.unlink(path)
            except FileNotFoundError:
                pass


@router.get("/config/models")
async def list_available_models(
    settings: Settings = Depends(get_settings),
):
    """List available BirdNET models."""
    models = [
        {
            "name": model_name,
            "active": model_name == settings.model,
            "supports_species_filter": model_supports_species_filter(model_name),
        }
        for model_name in list_installed_selectable_models()
    ]

    return {"models": models, "current": settings.model}


@router.get("/config/languages")
async def list_available_languages(
    settings: Settings = Depends(get_settings),
):
    """List available display languages."""
    l18n_dir = os.path.join(settings.model_path, 'l18n')

    languages = []
    for filename in os.listdir(l18n_dir):
        if filename.startswith('labels_') and filename.endswith('.json'):
            lang_code = filename.replace('labels_', '').replace('.json', '')
            languages.append({
                "code": lang_code,
                "active": lang_code == settings.database_lang,
            })

    languages.sort(key=lambda x: x['code'])

    return {"languages": languages, "current": settings.database_lang}


@router.get("/config/preview-species")
async def preview_species_list(
    threshold: float = Query(0.03, ge=0.0005, le=0.99),
    model: str | None = None,
    data_model_version: int | None = Query(None, ge=1, le=2),
    settings: Settings = Depends(get_settings),
):
    """Preview species list for a given threshold.

    Uses the species.py script to generate the list.
    """
    script_path = os.path.join(settings.base_path, 'scripts', 'species.py')
    python_path = os.path.join(settings.base_path, 'birdnet', 'bin', 'python3')
    model_name = model or settings.model
    model_version = data_model_version or settings.data_model_version

    if not model_supports_species_filter(model_name):
        raise HTTPException(status_code=400, detail=f"Model {model_name} does not support species range preview")

    cmd = [
        python_path,
        script_path,
        '--threshold',
        str(threshold),
        '--model',
        model_name,
        '--data-model-version',
        str(model_version),
        '--plain',
    ]

    try:
        result = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            timeout=60,
        )

        if result.returncode == 0:
            # Parse output - each line is a species
            species = [line.strip() for line in result.stdout.strip().split('\n') if line.strip()]
            return {
                "threshold": threshold,
                "model": model_name,
                "data_model_version": model_version,
                "count": len(species),
                "species": species,
            }
        else:
            raise HTTPException(status_code=500, detail=f"Script error: {result.stderr}")
    except subprocess.TimeoutExpired:
        raise HTTPException(status_code=500, detail="Species list generation timed out")
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))
