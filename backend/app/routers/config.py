APPRISE_BODY_FILENAME = 'body.txt'


def configured_birdnet_user(settings: Settings) -> str:
    return settings.config.get('BIRDNET_USER') or os.environ.get('USER', 'pi')


def run_managed_script(args: list[str], timeout: int, failure_detail: str) -> subprocess.CompletedProcess:
    try:
        result = subprocess.run(
            args,
            capture_output=True,
            text=True,
            timeout=timeout,
            check=False,
        )
    except subprocess.TimeoutExpired:
        raise HTTPException(status_code=500, detail=f"{failure_detail}: operation timed out")
    except Exception as exc:
        raise HTTPException(status_code=500, detail=f"{failure_detail}: {exc}")

    if result.returncode != 0:
        detail = result.stderr.strip() or result.stdout.strip() or "unknown error"
        raise HTTPException(status_code=500, detail=f"{failure_detail}: {detail}")

    return result


def sync_language_labels(settings: Settings) -> None:
    script_path = os.path.join(settings.base_path, 'scripts', 'install_language_label.sh')
    run_managed_script(
        ['sudo', '-u', configured_birdnet_user(settings), script_path],
        timeout=30,
        failure_detail="Failed to update model labels",
    )


def restart_services(settings: Settings) -> None:
    script_path = os.path.join(settings.base_path, 'scripts', 'restart_services.sh')
    run_managed_script(
        ['sudo', script_path],
        timeout=60,
        failure_detail="Failed to restart services",
    )


def caddy_site_addresses(raw_url: str) -> str:
    """Build the Caddy site-address line from the configured public URL."""
    candidate = (raw_url or '').strip().rstrip('/')
    if not candidate:
        return 'http://'

    parsed = urlparse(candidate if '://' in candidate else f'https://{candidate}')
    host = (parsed.netloc or parsed.path).strip().rstrip('/')
    if not host:
        return 'http://'

    return f'http:// {host}'


def update_caddy_config(settings: Settings) -> None:
    """Regenerate the FastAPI Caddyfile and reload Caddy."""
    auth_block = ''
    if settings.caddy_password:
        hash_result = run_managed_script(
            ['caddy', 'hash-password', '--plaintext', settings.caddy_password],
            timeout=10,
            failure_detail="Failed to hash Caddy password",
        )
        hashword = hash_result.stdout.strip()
        auth_block = f"""
  basicauth /api/config* {{
    birdnet {hashword}
  }}
  @protected_system {{
    path /api/system*
    not path /api/system/public-status*
  }}
  basicauth @protected_system {{
    birdnet {hashword}
  }}
  basicauth /settings* {{
    birdnet {hashword}
  }}"""

    caddyfile = f"""# BirdNET-Pi Caddy Configuration
# Generated by config API

{{
    admin off
}}

{caddy_site_addresses(settings.birdnetpi_url)} {{
    @blocked_legacy_probe_paths {{
        path_regexp legacyProbe (?i)(^|/)[^/]+\\.(php[0-9]?|phtml|phar|phps|phtm?)(/|$)|^/(\\.git|\\.env)(/|\\.|$)
    }}
    respond @blocked_legacy_probe_paths 404

    reverse_proxy localhost:8080
    {auth_block}

    encode gzip

    log {{
        output file /var/log/caddy/birdnet.log {{
            roll_size 10mb
            roll_keep 5
        }}
    }}
}}
"""

    with tempfile.NamedTemporaryFile(mode='w', delete=False, encoding='utf-8') as tmp:
        tmp.write(caddyfile)
        tmp_path = tmp.name

    try:
        run_managed_script(
            ['sudo', 'cp', tmp_path, '/etc/caddy/Caddyfile'],
            timeout=10,
            failure_detail="Failed to write Caddyfile",
        )
        run_managed_script(
            ['sudo', 'caddy', 'fmt', '--overwrite', '/etc/caddy/Caddyfile'],
            timeout=10,
            failure_detail="Failed to format Caddyfile",
        )
        run_managed_script(
            ['sudo', 'systemctl', 'reload', 'caddy'],
            timeout=20,
            failure_detail="Failed to reload Caddy",
        )
    finally:
        os.unlink(tmp_path)


def notification_file_path(settings: Settings, filename: str) -> str:
    return os.path.join(settings.base_path, filename)


def read_notification_file(settings: Settings, filename: str) -> str:
    path = notification_file_path(settings, filename)
    try:
        with open(path, 'r', encoding='utf-8') as handle:
            return handle.read()
    except FileNotFoundError:
        return ''


def write_notification_file(settings: Settings, filename: str, contents: str) -> None:
    path = notification_file_path(settings, filename)
    with open(path, 'w', encoding='utf-8') as handle:
        handle.write(contents)


def serialize_config_value(field: str, key: str, value) -> str:
    if field == 'activate_freqshift_in_livestream':
        rendered = '"true"' if value else '"false"'
    elif isinstance(value, bool):
        rendered = '1' if value else '0'
    elif isinstance(value, str):
        rendered = f'{key}="{value}"'
        return rendered
    else:
        rendered = str(value)

    return f'{key}={rendered}'


